const crypto = require("crypto");

// Derive a fixed 32-byte key and 16-byte IV from environment secrets
const SECRET = process.env.ENCRYPTION_KEY || process.env.JWT_SECRET;
const KEY = crypto.createHash("sha256").update(SECRET).digest(); // 32 bytes

/**
 * Encrypt a plain text string using AES-256-CBC
 * Returns hex string format: "iv_hex:encrypted_hex"
 */
function encrypt(plainText) {
  if (!plainText) return null;
  const iv = crypto.randomBytes(16);
  const cipher = crypto.createCipheriv("aes-256-cbc", KEY, iv);
  let encrypted = cipher.update(String(plainText), "utf8", "hex");
  encrypted += cipher.final("hex");
  return `${iv.toString("hex")}:${encrypted}`;
}

/**
 * Decrypt an encrypted string generated by encrypt()
 */
function decrypt(cipherText) {
  if (!cipherText || !cipherText.includes(":")) return null;
  try {
    const [ivHex, encrypted] = cipherText.split(":");
    const iv = Buffer.from(ivHex, "hex");
    const decipher = crypto.createDecipheriv("aes-256-cbc", KEY, iv);
    let decrypted = decipher.update(encrypted, "hex", "utf8");
    decrypted += decipher.final("utf8");
    return decrypted;
  } catch (err) {
    console.error("Decryption error:", err.message);
    return null;
  }
}

/**
 * Mask database URI to hide passwords for secure UI display
 * e.g. "mongodb+srv://user:secretpass@cluster..." -> "mongodb+srv://user:******@cluster..."
 */
function maskDatabaseUri(uri) {
  if (!uri || typeof uri !== "string") return null;
  return uri.replace(/(:\/\/[^:]+:)([^@]+)(@)/, "$1******$3");
}

module.exports = {
  encrypt,
  decrypt,
  maskDatabaseUri,
};

